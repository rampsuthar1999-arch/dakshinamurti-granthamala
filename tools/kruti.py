CONS = "कखगघङचछजझञटठडढणतथदधनपफबभमयरलळवशषसहक़ख़ग़ज़ड़ढ़फ़य़ऱऩ"
MATRAS = "ािीुूृेैोौंःँॅ़"
_ONE = sorted(set(p[0] for p in PAIRS), key=len, reverse=True)
_MAP = {}
for a, b in PAIRS:
    _MAP.setdefault(a, b)  # first wins (same as sequential replace order for duplicates)
_RX = re.compile('|'.join(re.escape(x) for x in _ONE))


def _seq_replace(s):
    # The classic converter replaces sequentially in array order; a greedy longest-match
    # tokenizer gives the same result for this table and is much faster.
    return _RX.sub(lambda m: _MAP[m.group(0)], s)


def convert(s, tra_short=False):
    if tra_short:  # Narad/Shiva (Kṛṣṇa Sandesh): '=k' is त्र, '=kk' is त्रा
        s = s.replace('=kk', '\x01').replace('=k', '=').replace('\x01', '=k')
    s = s.replace('=kk', '=k').replace('f=k', 'f=').replace('=kh', '=h')
    s = s.replace('±', 'Zं').replace('Æ', 'र्f')
    s = _seq_replace(s)
    s = s.replace('्ा', '')
    # choti-i: 'f' precedes the consonant cluster it belongs to
    s = re.sub(r'f((?:[%s]्)*[%s]़?)' % (CONS, CONS), r'\1ि', s)
    s = s.replace('f', 'ि')  # stray
    # reph: 'Z' follows the syllable (consonant cluster + matras) it sits on
    s = re.sub(r'((?:[%s]्)*[%s]़?[%s]*)Z' % (CONS, CONS, MATRAS), r'र्\1', s)
    s = s.replace('Z', 'र्')
    # cleanups
    s = s.replace('्ा', '').replace('ाे', 'ो').replace('ंै', 'ैं').replace('ाें', 'ों').replace('ाें', 'ों').replace('ेे', 'े').replace('ाै', 'ौ').replace('ंु', 'ुं').replace('ंे', 'ें')
    s = s.replace('अा', 'आ').replace('एे', 'ऐ').replace('आे', 'ओ').replace('आै', 'औ')
    s = re.sub(r'ि्', '्ि', s)
    s = re.sub(r'ा(ं?)े', r'ो\1', s)
    s = re.sub(r'ा(ं?)ै', r'ौ\1', s)
    s = s.replace('।।', '॥').replace(' ः', ':').replace('्र्र', '्र').replace('µ', '—')
    s = s.translate(str.maketrans('0123456789', '०१२३४५६७८९'))
    for _ in range(2):
        s = re.sub(r'([०-९])ॉ', r'\1०', s)  # Narad/Shiva draw zero with the ‚ glyph
    return s


